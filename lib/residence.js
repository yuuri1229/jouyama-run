// =========================================================
// 住所 → サイトに載せる「居住地」への変換
// ---------------------------------------------------------
// 管理シートには住所が丸ごと入っているため、そのまま載せない。
//   ・新潟県内  → 市町村名だけ（例：新潟市、燕市、弥彦村）
//   ・新潟県外  → 都道府県名だけ（例：東京都）
//   ・判別できない → 空文字（サイトでは「—」）。住所の一部を推測で出さない
// 区・番地・建物名などはここで必ず捨てる。
// =========================================================

const PREFECTURES = [
  "北海道", "青森県", "岩手県", "宮城県", "秋田県", "山形県", "福島県",
  "茨城県", "栃木県", "群馬県", "埼玉県", "千葉県", "東京都", "神奈川県",
  "新潟県", "富山県", "石川県", "福井県", "山梨県", "長野県", "岐阜県",
  "静岡県", "愛知県", "三重県", "滋賀県", "京都府", "大阪府", "兵庫県",
  "奈良県", "和歌山県", "鳥取県", "島根県", "岡山県", "広島県", "山口県",
  "徳島県", "香川県", "愛媛県", "高知県", "福岡県", "佐賀県", "長崎県",
  "熊本県", "大分県", "宮崎県", "鹿児島県", "沖縄県",
];

// 新潟県内の市町村（20市・6町・4村）。郡名は付けずに載せる。
// 「十日町市」のように名前に「町」を含む市があるため、
// 「市・町・村の文字で区切る」方式ではなく一覧と突き合わせる。
const NIIGATA_MUNICIPALITIES = [
  "新潟市", "長岡市", "三条市", "柏崎市", "新発田市", "小千谷市", "加茂市",
  "十日町市", "見附市", "村上市", "燕市", "糸魚川市", "妙高市", "五泉市",
  "上越市", "阿賀野市", "佐渡市", "魚沼市", "南魚沼市", "胎内市",
  "聖籠町", "弥彦村", "田上町", "阿賀町", "出雲崎町", "湯沢町", "津南町",
  "刈羽村", "関川村", "粟島浦村",
];
// 郡の名前（住所が「西蒲原郡弥彦村…」のように郡から始まる場合に読み飛ばす）
const NIIGATA_GUN = /^(北蒲原郡|西蒲原郡|南蒲原郡|東蒲原郡|三島郡|南魚沼郡|中魚沼郡|刈羽郡|岩船郡)/;

// 「南魚沼市」が「魚沼市」より先に当たるよう、長い名前から順に試す
const byLength = [...NIIGATA_MUNICIPALITIES].sort((a, b) => b.length - a.length);
const niigataMunicipality = (s) => {
  const rest = s.replace(NIIGATA_GUN, "");
  return byLength.find((m) => rest.startsWith(m)) || "";
};

export function toResidence(address) {
  // 全角英数・空白の揺れをそろえ、郵便番号（〒950-0000 など）を外す
  const s = String(address ?? "")
    .normalize("NFKC")
    .replace(/\s+/g, "")
    .replace(/^〒?\d{3}-?\d{4}/, "");
  if (!s) return "";

  const pref = PREFECTURES.find((p) => s.startsWith(p));
  if (pref === "新潟県") return niigataMunicipality(s.slice(pref.length));
  if (pref) return pref;

  // 都道府県が省略された住所。新潟県内の市町村名で始まるときだけ扱う
  return niigataMunicipality(s);
}
